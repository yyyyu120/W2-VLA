def collate_fn(batch):
    return batch


def _resolve_npz_path(label_dir: Path, dataset_name: str, episode_index: int) -> Optional[Path]:
    path = label_dir / dataset_name / f"episode_{episode_index:06d}.npz"
    return path if path.exists() else None


def _get_frame_value(data: Dict, key: str, step: int, default):
    value = data.get(key, default)
    if isinstance(value, np.ndarray) and value.ndim > 0:
        if step < len(value):
            return value[step]
        return value[-1]
    return value


def _as_str(value) -> str:
    if isinstance(value, np.ndarray):
        if value.shape == ():
            value = value.item()
        elif len(value) > 0:
            value = value[0]
    return str(value) if value is not None else ""


def _as_bool(value, default: bool = False) -> bool:
    if value is None:
        return default
    if isinstance(value, str):
        return value.strip().lower() not in {"", "0", "false", "no", "off"}
    return bool(value)


def _build_wrist_cot(
    target: str,
    where: str,
    phase: str,
    wrist_focus: str,
    next_trend: str,
    target_where: str = "",
    goal: str = "",
    goal_where: str = "",
    contact_state: str = "",
    subtask: str = "",
) -> str:
    target = (target or "target object").strip()
    phase = (phase or "approach").strip().lower()
    goal = (goal or "workspace").strip()
    subtask = (subtask or "").strip()
    if not subtask:
        if phase == "contact":
            subtask = f"grasp the {target}"
        elif phase == "move" and goal and goal != "workspace":
            subtask = f"move the {target} toward the {goal}"
        elif phase == "align" and goal and goal != "workspace":
            subtask = f"align the {target} with the {goal}"
        elif phase == "release" and goal and goal != "workspace":
            subtask = f"release the {target} at the {goal}"
        elif phase in {"pull", "push"}:
            subtask = f"{phase} the {target}"
        else:
            subtask = f"reach toward the {target}"

    if phase == "approach":
        reasoning = f"The gripper is approaching the {target}; use the wrist view to localize it before contact."
    elif phase == "contact":
        reasoning = f"The gripper is at the {target}; close around it before the next motion."
    elif phase == "move":
        reasoning = f"The {target} is held; keep it stable while moving toward the goal."
    elif phase == "align":
        reasoning = f"The {target} is near the goal; refine the relative pose before release."
    elif phase == "release":
        reasoning = f"The {target} is aligned with the goal; open the gripper after it is stable."
    elif phase in {"pull", "push"}:
        reasoning = f"The gripper is controlling the {target}; continue the {phase} motion."
    else:
        reasoning = f"Follow the current physical stage for the {target}."
    return f"Subtask: {subtask}. Reasoning: {reasoning} Wrist: {wrist_focus}."


def _normalize_phase(value: str) -> str:
    value = (value or "").strip().lower()
    aliases = {
        "approach_object": "approach",
        "grasp": "contact",
        "transport": "move",
        "align_to_goal": "align",
        "place": "release",
        "finished": "done",
    }
    value = aliases.get(value, value)
    if value in {"approach", "align", "contact", "pull", "push", "move", "release", "done"}:
        return value
    if value in {"open", "close", "press", "pick", "place", "manipulate"}:
        return "approach"
    return value or "approach"


def load_subtask_label_data(
    label_dir: Path,
    dataset_name: str,
    episode_index: int,
) -> Optional[Dict]:
    if label_dir is None:
        return None

    npz_path = _resolve_npz_path(Path(label_dir), dataset_name, episode_index)
    if npz_path is None:
        return None

    try:
        raw = np.load(npz_path, allow_pickle=True)
        return {key: raw[key] for key in raw.files}
    except Exception as exc:
        print(f"Warning: failed to load subtask labels from {npz_path}: {exc}")
        return None


class SubtaskM2WMixDataset(LeRobotMixtureDataset):
    """
    LeRobotMixtureDataset with Subtask-Guided Main-to-Wrist annotations.

    Sample fields:
        image: main-view PIL images only
        wrist_views: current wrist-view PIL images
        future_wrist_views: future wrist-view PIL images for latent target
        cot_target: training assistant text, preferring cot_train_text
        cot_debug_text: structured assistant text for inspection
        cot_target_object / cot_where / cot_phase / cot_wrist_focus / cot_next_trend:
            parsed structured fields used by analysis and ablations
    """

    def __init__(self, *args, subtask_label_dir: str = None, **kwargs):
        super().__init__(*args, **kwargs)
        self.subtask_label_dir = Path(subtask_label_dir) if subtask_label_dir else None
        print(f"SubtaskM2WMixDataset | subtask_label_dir={subtask_label_dir}")

    def _extract_images(self, data: Dict, video_keys) -> tuple[list[Image.Image], list[Image.Image]]:
        prim_images = []
        wrist_views = []
        for video_key in video_keys:
            image = data[video_key][0]
            pil = Image.fromarray(image)
            if "wrist" in video_key:
                wrist_views.append(pil)
            else:
                prim_images.append(pil)
        return prim_images, wrist_views

    def _load_future_wrist_views(
        self,
        dataset,
        trajectory_id: int,
        future_step: int,
        history_frames: int = 1,
    ):
        if history_frames > 1:
            history_steps = self._history_steps(dataset, trajectory_id, future_step, history_frames)
            try:
                return self._load_wrist_views_at_steps(dataset, trajectory_id, history_steps)
            except Exception:
                pass

        future_wrist = self._load_wrist_views_at_step(dataset, trajectory_id, future_step)
        return self._load_wrist_history_views(
            dataset=dataset,
            trajectory_id=trajectory_id,
            step=future_step,
            current_wrist_views=future_wrist,
            history_frames=history_frames,
        )

    def _history_steps(self, dataset, trajectory_id: int, step: int, history_frames: int) -> list[int]:
        traj_index = dataset.get_trajectory_index(trajectory_id)
        max_step = int(dataset.trajectory_lengths[traj_index]) - 1
        return [
            min(max(0, int(step) - offset), max_step)
            for offset in range(history_frames - 1, -1, -1)
        ]

    def _wrist_video_keys(self, dataset) -> list[str]:
        video_keys = list(dataset.modality_keys["video"])
        wrist_keys = [key for key in video_keys if "wrist" in key.lower()]
        return wrist_keys or video_keys

    def _load_wrist_views_at_steps(self, dataset, trajectory_id: int, steps: list[int]):
        if not steps:
            return []

        traj_data = dataset.get_trajectory_data(trajectory_id)
        dataset.curr_traj_data = traj_data
        timestamps = traj_data["timestamp"].to_numpy()[np.asarray(steps, dtype=np.int64)]

        history_views = []
        for video_key in self._wrist_video_keys(dataset):
            key = video_key.replace("video.", "")
            video_path = dataset.get_video_path(trajectory_id, key)
            frames = get_frames_by_timestamps(
                video_path.as_posix(),
                timestamps,
                video_backend=dataset.video_backend,
                video_backend_kwargs=dataset.video_backend_kwargs,
            )
            history_views.append([Image.fromarray(frame) for frame in frames])
        return history_views

    def _load_wrist_views_at_step(self, dataset, trajectory_id: int, step: int):
        raw = dataset.get_step_data(trajectory_id, step)
        data = dataset.transforms(raw)
        prim_images, wrist_views = self._extract_images(data, dataset.modality_keys["video"])
        return wrist_views if wrist_views else prim_images

    def _load_wrist_history_views(
        self,
        dataset,
        trajectory_id: int,
        step: int,
        current_wrist_views: list[Image.Image],
        history_frames: int,
    ):
        if history_frames <= 1:
            return current_wrist_views

        history_steps = self._history_steps(dataset, trajectory_id, step, history_frames)
        try:
            return self._load_wrist_views_at_steps(dataset, trajectory_id, history_steps)
        except Exception:
            pass

        per_step_views = []
        for hist_step in history_steps:
            if hist_step == step:
                per_step_views.append(current_wrist_views)
            else:
                per_step_views.append(self._load_wrist_views_at_step(dataset, trajectory_id, hist_step))

        num_views = max(len(views) for views in per_step_views)
        history_views = []
        for view_idx in range(num_views):
            clip = []
            for views in per_step_views:
                clip.append(views[view_idx] if view_idx < len(views) else views[-1])
            history_views.append(clip)
        return history_views

    def _future_gap_loss_weight(self, gap: int) -> float:
        """Reliability weight for future wrist latent supervision.

        The future target is an 8-frame window ending at the selected future
        step. At a segment boundary there may be no valid future in the same
        subtask, and very small gaps overlap heavily with the current window.
        """
        if gap <= 0:
            return 0.0
        if self.data_cfg is None:
            small_gap = 2
            small_gap_weight = 0.5
        else:
            small_gap = int(self.data_cfg.get("future_wrist_small_gap", 2))
            small_gap_weight = float(self.data_cfg.get("future_wrist_small_gap_weight", 0.5))
        return small_gap_weight if gap <= small_gap else 1.0

    def _default_labels(self, language: str) -> Dict:
        cot_target = _build_wrist_cot(
            target="target object",
            where="workspace",
            phase="approach",
            wrist_focus="search for the target object",
            next_trend="follow the instruction",
        )
        return {
            "primitive_label": 6,
            "confidence": 0.0,
            "spatial_vector": [0.0, 0.0, 0.0],
            "object_phrase": "target object",
            "goal_phrase": "workspace",
            "cot_target": cot_target,
            "cot_train_text": cot_target,
            "cot_debug_text": cot_target,
            "cot_text": cot_target,
            "cot_target_object": "target object",
            "cot_target_where": "workspace",
            "cot_goal_object": "workspace",
            "cot_goal_where": "workspace",
            "cot_where": "workspace",
            "cot_phase": "approach",
            "cot_wrist_focus": "search for the target object",
            "cot_next_trend": "follow the instruction",
            "cot_contact_state": "uncertain",
            "cot_main_observation": "",
            "cot_wrist_observation": "",
            "vlm_annotation_source": "rule",
            "vlm_confidence": 0.0,
            "vlm_keyframe_index": -1,
            "coarse_motion": "hold position",
            "cot_subtask": language,
            "cot_reasoning": "",
            "cot_primitive": "manipulate",
            "cot_object": "target object",
            "cot_anchor": "workspace",
            "cot_affordance": "contact region",
            "cot_trend": "follow the instruction",
            "future_wrist_index": None,
            "subgoal_wrist_index": None,
            "segment_id": 0,
            "segment_start_index": 0,
            "segment_end_index": 0,
            "segment_progress": 0.0,
            "temporal_anchor": "alignment",
        }

    def _labels_for_step(self, label_data: Optional[Dict], step: int, language: str) -> Dict:
        labels = self._default_labels(language)
        if label_data is None:
            return labels

        num_frames = int(_get_frame_value(label_data, "num_frames", step, 0))
        valid_step = step < num_frames if num_frames > 0 else True
        if not valid_step:
            return labels

        target_object = _as_str(
            _get_frame_value(
                label_data,
                "cot_target_object",
                step,
                _get_frame_value(label_data, "cot_object", step, "target object"),
            )
        )
        where = _as_str(
            _get_frame_value(
                label_data,
                "cot_where",
                step,
                _get_frame_value(label_data, "cot_anchor", step, "workspace"),
            )
        )
        target_where = _as_str(
            _get_frame_value(label_data, "cot_target_where", step, where)
        )
        goal_object = _as_str(
            _get_frame_value(
                label_data,
                "cot_goal_object",
                step,
                _get_frame_value(label_data, "goal_phrase", step, "workspace"),
            )
        )
        goal_where = _as_str(
            _get_frame_value(label_data, "cot_goal_where", step, goal_object)
        )
        phase = _normalize_phase(
            _as_str(
                _get_frame_value(
                    label_data,
                    "cot_phase",
                    step,
                    _get_frame_value(label_data, "cot_primitive", step, "approach"),
                )
            )
        )
        wrist_focus = _as_str(
            _get_frame_value(
                label_data,
                "cot_wrist_focus",
                step,
                _get_frame_value(label_data, "cot_affordance", step, "local target evidence"),
            )
        )
        next_trend = _as_str(
            _get_frame_value(
                label_data,
                "cot_next_trend",
                step,
                _get_frame_value(label_data, "cot_trend", step, "follow the instruction"),
            )
        )
        coarse_motion = _as_str(
            _get_frame_value(label_data, "coarse_motion", step, next_trend)
        )
        has_v2_fields = "cot_target_object" in label_data or "cot_phase" in label_data
        cot_target = _as_str(
            _get_frame_value(label_data, "cot_target", step, "") if has_v2_fields else ""
        )
        if not cot_target or cot_target.lstrip().startswith("<"):
            cot_target = _build_wrist_cot(
                target=target_object,
                where=where,
                phase=phase,
                wrist_focus=wrist_focus,
                next_trend=next_trend,
                target_where=target_where,
                goal=goal_object,
                goal_where=goal_where,
            )
        cot_train_text = _as_str(_get_frame_value(label_data, "cot_train_text", step, ""))
        cot_debug_text = cot_target
        cot_target_for_training = cot_train_text or cot_target

        labels.update(
            {
                "primitive_label": int(_get_frame_value(label_data, "primitive_labels", step, 6)),
                "confidence": float(_get_frame_value(label_data, "confidence", step, 0.0)),
                "spatial_vector": np.asarray(
                    _get_frame_value(label_data, "spatial_vectors", step, [0.0, 0.0, 0.0]),
                    dtype=np.float32,
                ).tolist(),
                "object_phrase": _as_str(label_data.get("object_phrase", "target object")),
                "goal_phrase": _as_str(label_data.get("goal_phrase", "workspace")),
                "cot_target": cot_target_for_training,
                "cot_train_text": cot_target_for_training,
                "cot_debug_text": cot_debug_text,
                "cot_text": _as_str(_get_frame_value(label_data, "cot_text", step, cot_target)),
                "cot_target_object": target_object,
                "cot_target_where": target_where,
                "cot_goal_object": goal_object,
                "cot_goal_where": goal_where,
                "cot_where": where,
                "cot_phase": phase,
                "cot_wrist_focus": wrist_focus,
                "cot_next_trend": next_trend,
                "cot_contact_state": _as_str(
                    _get_frame_value(label_data, "cot_contact_state", step, "uncertain")
                ),
                "cot_main_observation": _as_str(
                    _get_frame_value(label_data, "cot_main_observation", step, "")
                ),
                "cot_wrist_observation": _as_str(
                    _get_frame_value(label_data, "cot_wrist_observation", step, "")
                ),
                "vlm_annotation_source": _as_str(
                    _get_frame_value(label_data, "vlm_annotation_source", step, "rule")
                ),
                "vlm_confidence": float(
                    _get_frame_value(label_data, "vlm_confidence", step, 0.0)
                ),
                "vlm_keyframe_index": int(
                    _get_frame_value(label_data, "vlm_keyframe_indices", step, -1)
                ),
                "coarse_motion": coarse_motion,
                "cot_subtask": _as_str(_get_frame_value(label_data, "cot_subtask", step, language)),
                "cot_reasoning": _as_str(_get_frame_value(label_data, "cot_reasoning", step, "")),
                "cot_primitive": _as_str(_get_frame_value(label_data, "cot_primitive", step, "manipulate")),
                "cot_object": _as_str(_get_frame_value(label_data, "cot_object", step, "target object")),
                "cot_anchor": _as_str(_get_frame_value(label_data, "cot_anchor", step, "workspace")),
                "cot_affordance": _as_str(
                    _get_frame_value(label_data, "cot_affordance", step, "contact region")
                ),
                "cot_trend": _as_str(_get_frame_value(label_data, "cot_trend", step, "follow the instruction")),
                "future_wrist_index": (
                    int(_get_frame_value(label_data, "future_wrist_indices", step, step))
                    if "future_wrist_indices" in label_data
                    else None
                ),
                "subgoal_wrist_index": (
                    int(_get_frame_value(label_data, "subgoal_wrist_indices", step, step))
                    if "subgoal_wrist_indices" in label_data
                    else None
                ),
                "segment_id": int(_get_frame_value(label_data, "segment_ids", step, 0)),
                "segment_start_index": int(
                    _get_frame_value(label_data, "segment_start_indices", step, 0)
                ),
                "segment_end_index": int(
                    _get_frame_value(label_data, "segment_end_indices", step, step)
                ),
                "segment_progress": float(
                    _get_frame_value(label_data, "segment_progress", step, 0.0)
                ),
                "temporal_anchor": _as_str(
                    _get_frame_value(label_data, "temporal_anchor", step, "alignment")
                ),
                "semantic_motion_stage": _as_str(
                    _get_frame_value(label_data, "semantic_motion_stages", step, phase)
                ),
            }
        )
        return labels

    def __getitem__(self, index: int) -> dict:
        max_retries = 10
        last_exception = None

        for attempt in range(max_retries):
            try:
                video_search_retries = 0
                while video_search_retries < 100:
                    dataset, trajectory_id, step = self.sample_step(index)
                    key = dataset.modality_keys["video"][0].replace("video.", "")
                    video_path = dataset.get_video_path(trajectory_id, key)
                    if os.path.exists(video_path):
                        break
                    index = random.randint(0, len(self) - 1)
                    video_search_retries += 1

                raw_data = dataset.get_step_data(trajectory_id, step)
                data = dataset.transforms(raw_data)
                prim_images, wrist_views = self._extract_images(data, dataset.modality_keys["video"])
                if not wrist_views:
                    wrist_views = prim_images
                load_wrist_future_views = (
                    _as_bool(self.data_cfg.get("load_wrist_future_views", True), True)
                    if self.data_cfg
                    else True
                )
                history_frames = int(self.data_cfg.get("wrist_history_frames", 1)) if self.data_cfg else 1
                if load_wrist_future_views:
                    wrist_history_views = self._load_wrist_history_views(
                        dataset=dataset,
                        trajectory_id=trajectory_id,
                        step=step,
                        current_wrist_views=wrist_views,
                        history_frames=history_frames,
                    )
                else:
                    # CoT-only / qwen-only ablations should match the base
                    # dual-view VLA input: current main view + current wrist
                    # view only.  Avoid reading history/future wrist clips that
                    # are unused by the model and can dominate dataloader IO.
                    history_frames = 1
                    wrist_history_views = wrist_views

                language = data[dataset.modality_keys["language"][0]][0]
                action = np.concatenate(
                    [data[k] for k in dataset.modality_keys["action"]], axis=1
                ).astype(np.float16)

                label_data = load_subtask_label_data(
                    self.subtask_label_dir,
                    dataset.dataset_name,
                    trajectory_id,
                )
                labels = self._labels_for_step(label_data, step, language)

                traj_index = dataset.get_trajectory_index(trajectory_id)
                max_step = int(dataset.trajectory_lengths[traj_index]) - 1
                k = int(self.data_cfg.get("future_wrist_k", 8)) if self.data_cfg else 8
                if load_wrist_future_views:
                    future_target = (
                        self.data_cfg.get("future_wrist_target", "clipped_short_horizon")
                        if self.data_cfg
                        else "clipped_short_horizon"
                    )
                    future_target = str(future_target).lower()

                    if future_target in {"subgoal", "segment_end"}:
                        future_step = labels.get("subgoal_wrist_index")
                    elif future_target in {"short_horizon", "fixed_short_horizon", "t_plus_k"}:
                        # Phase-agnostic target used by v8: always predict K steps
                        # ahead, clamped only by the episode boundary.
                        future_step = min(step + k, max_step)
                    elif future_target in {"clipped_short_horizon", "segment_clipped", "valid_short_horizon"}:
                        future_step = labels.get("future_wrist_index")
                        if future_step is None:
                            future_step = min(step + k, max_step)
                        subgoal_step = labels.get("subgoal_wrist_index")
                        if subgoal_step is not None:
                            future_step = min(int(future_step), int(subgoal_step))
                    else:
                        future_step = labels.get("future_wrist_index")

                    if future_step is None:
                        future_step = min(step + k, max_step)
                    future_step = min(max(0, int(future_step)), max_step)
                    future_gap = int(future_step) - int(step)
                    future_wrist_loss_weight = self._future_gap_loss_weight(future_gap)
                    if future_target in {"short_horizon", "fixed_short_horizon", "t_plus_k"}:
                        # The v8 predictor has no horizon input and represents one
                        # fixed transition, t -> t+K. Episode-tail samples with a
                        # shorter gap still train the action loss but not L_wrist.
                        future_wrist_loss_weight = 1.0 if future_gap == k else 0.0
                    future_step_for_loading = future_step if future_gap > 0 else int(step)
                    future_wrist_views = self._load_future_wrist_views(
                        dataset,
                        trajectory_id,
                        int(future_step_for_loading),
                        history_frames=history_frames,
                    )
                    if not future_wrist_views:
                        future_wrist_views = wrist_history_views
                else:
                    future_step_for_loading = int(step)
                    future_gap = 0
                    future_wrist_loss_weight = 0.0
                    future_wrist_views = wrist_history_views

                result = {
                    "image": prim_images,
                    "wrist_views": wrist_history_views,
                    "future_wrist_views": future_wrist_views,
                    "future_wrist_resolved_index": int(future_step_for_loading),
                    "future_wrist_gap": int(future_gap),
                    "future_wrist_loss_weight": float(future_wrist_loss_weight),
                    "lang": language,
                    "action": action,
                    **labels,
                }

                if self.data_cfg is not None and self.data_cfg.get("include_state", False) not in ["False", False]:
                    state = np.concatenate(
                        [data[k] for k in dataset.modality_keys["state"]], axis=1
                    ).astype(np.float16)
                    result["state"] = state

                return result

            except Exception as exc:
                last_exception = exc
                index = random.randint(0, len(self) - 1)
                if attempt == max_retries - 1:
                    raise last_exception


def _make_single_dataset(
    data_root_dir,
    data_name,
    robot_type,
    delete_pause_frame=False,
    data_cfg=None,
) -> LeRobotSingleDataset:
    data_config = ROBOT_TYPE_CONFIG_MAP[robot_type]
    modality_config = data_config.modality_config()
    transforms = data_config.transform()
    dataset_path = data_root_dir / data_name

    if robot_type not in ROBOT_TYPE_TO_EMBODIMENT_TAG:
        embodiment_tag = EmbodimentTag.NEW_EMBODIMENT
    else:
        embodiment_tag = ROBOT_TYPE_TO_EMBODIMENT_TAG[robot_type]

    video_backend = data_cfg.get("video_backend", "decord") if data_cfg else "decord"

    return LeRobotSingleDataset(
        dataset_path=dataset_path,
        modality_configs=modality_config,
        transforms=transforms,
        embodiment_tag=embodiment_tag,
        video_backend=video_backend,
        delete_pause_frame=delete_pause_frame,
        data_cfg=data_cfg,
    )


def get_vla_dataset(
    data_cfg,
    mode: str = "train",
    balance_dataset_weights: bool = False,
    balance_trajectory_weights: bool = False,
    seed: int = 42,
    **kwargs,
) -> SubtaskM2WMixDataset:
    data_root_dir = Path(data_cfg.data_root_dir)
    data_mix = data_cfg.data_mix
    subtask_label_dir = data_cfg.get("subtask_label_dir", None)
    delete_pause = data_cfg.get("delete_pause_frame", False)

    mixture_spec = DATASET_NAMED_MIXTURES[data_mix]
    seen, filtered = set(), []
    for d_name, d_weight, robot_type in mixture_spec:
        key = (d_name, robot_type)
        if key in seen:
            continue
        seen.add(key)
        filtered.append((d_name, d_weight, robot_type))

    dataset_mixture = [
        (
            _make_single_dataset(
                data_root_dir,
                d_name,
                robot_type,
                delete_pause_frame=delete_pause,
                data_cfg=data_cfg,
            ),
            d_weight,
        )
        for d_name, d_weight, robot_type in filtered
    ]

    return SubtaskM2WMixDataset(
        dataset_mixture,
        mode=mode,
        balance_dataset_weights=balance_dataset_weights,
        balance_trajectory_weights=balance_trajectory_weights,
        seed=seed,
        data_cfg=data_cfg,
        subtask_label_dir=subtask_label_dir,
        **kwargs,
    )
